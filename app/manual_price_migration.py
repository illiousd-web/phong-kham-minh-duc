"""Version 4: nullable service-charge snapshots and auditable manual prices.

PostgreSQL uses the caller's owner transaction/advisory lock. SQLite rebuilds
only the three affected tables in one offline transaction, checking every FK
before commit. Down refuses new-feature data instead of deleting or repricing it.
"""
from pathlib import Path
import re
import sqlite3

ROOT = Path(__file__).resolve().parents[1]
NULLABLE = {'charges': 'amount', 'orders': 'proposed_price', 'order_authorizations': 'unit_price'}
CATEGORIES = {'service_categories': "'consultation','lab','ultrasound','xray','ecg'"}
FLAG = 'price_at_collection'
# Loại giao dịch lưu lúc thu: thu thường / thu tạm (còn khoản chưa có giá) / ứng trước.
# Dữ liệu cũ: is_advance=1 là ứng trước, còn lại là thu thường (trước v4 chưa có thu tạm).
PAYMENT_KIND = "kind TEXT NOT NULL DEFAULT 'regular' CHECK(kind IN ('regular','provisional','advance'))"
VIEW = """CREATE VIEW effective_charges AS SELECT ch.id,ch.visit_id,ch.label,ch.created_at,
CASE WHEN EXISTS(SELECT 1 FROM charge_voids v WHERE v.charge_id=ch.id) THEN 0
ELSE COALESCE((SELECT p.amount FROM charge_pricing p WHERE p.charge_id=ch.id),
(SELECT mp.amount FROM manual_charge_prices mp WHERE mp.charge_id=ch.id),ch.amount)
-COALESCE((SELECT SUM(cr.amount) FROM charge_credits cr WHERE cr.charge_id=ch.id),0) END AS amount,
ch.amount AS original_amount FROM charges ch"""
OLD_VIEW = VIEW.replace('(SELECT mp.amount FROM manual_charge_prices mp WHERE mp.charge_id=ch.id),', '')


def down_guard(c):
    if c.execute("SELECT 1 FROM service_categories WHERE category='procedure' LIMIT 1").fetchone() or c.execute("SELECT 1 FROM orders WHERE category IN ('consultation','procedure') LIMIT 1").fetchone():
        raise ValueError('Không thể quay lui: đã có nhóm/chỉ định mới; hãy khôi phục bản sao lưu trước nâng cấp')
    if c.execute('SELECT 1 FROM service_catalog WHERE price_at_collection=1 LIMIT 1').fetchone():
        raise ValueError('Không thể quay lui: đã có dịch vụ giá nhập khi thu; giữ bản mới hoặc khôi phục bản sao lưu trước nâng cấp')
    for table, column in NULLABLE.items():
        if c.execute(f'SELECT 1 FROM {table} WHERE {column} IS NULL LIMIT 1').fetchone():
            raise ValueError('Không thể quay lui: còn khoản/chỉ định chưa có giá; không được chuyển thành 0 hoặc xóa dữ liệu')
    if c.execute("SELECT 1 FROM payments WHERE kind='provisional' LIMIT 1").fetchone():
        raise ValueError('Không thể quay lui: đã có phiếu thu tạm; bản cũ không phân biệt được thu tạm với thu thường')
    for table in ('manual_charge_prices', 'manual_price_requests'):
        if c.execute(f'SELECT 1 FROM {table} LIMIT 1').fetchone():
            raise ValueError('Không thể quay lui: đã có lịch sử giá nhập tay; hãy khôi phục bản sao lưu trước nâng cấp')


def migrate_manual_prices(c, *, postgres=False, down=False):
    applied = bool(c.execute('SELECT 1 FROM schema_migrations WHERE version=4').fetchone())
    if applied == (not down):
        return
    if not postgres:
        raise ValueError('SQLite phải dùng migrate_sqlite_manual_prices để giữ giao dịch và khóa ngoại')
    if down:
        down_guard(c)
    c.execute('DROP VIEW effective_charges')
    if down:
        c.execute(OLD_VIEW)
        c.execute('DROP TABLE manual_price_requests')
        c.execute('DROP TABLE manual_charge_prices')
        for table, original in CATEGORIES.items():
            c.execute(f'ALTER TABLE {table} DROP CONSTRAINT {table}_category_check')
            c.execute(f'ALTER TABLE {table} ADD CONSTRAINT {table}_category_check CHECK(category IN ({original}))')
        for table, column in NULLABLE.items():
            c.execute(f'ALTER TABLE {table} ALTER COLUMN {column} SET NOT NULL')
        c.execute('ALTER TABLE service_catalog DROP COLUMN price_at_collection')
        c.execute('ALTER TABLE payments DROP COLUMN kind')
        c.execute('DROP INDEX IF EXISTS idx_charges_visit')
        c.execute('DELETE FROM schema_migrations WHERE version=4')
        return
    c.execute('ALTER TABLE service_catalog ADD COLUMN price_at_collection INTEGER NOT NULL DEFAULT 0 CHECK(price_at_collection IN (0,1))')
    c.execute('ALTER TABLE payments ADD COLUMN ' + PAYMENT_KIND)
    c.execute("UPDATE payments SET kind='advance' WHERE is_advance=1")
    for table, original in CATEGORIES.items():
        allowed = original + ",'procedure'"
        c.execute(f'ALTER TABLE {table} DROP CONSTRAINT {table}_category_check')
        c.execute(f'ALTER TABLE {table} ADD CONSTRAINT {table}_category_check CHECK(category IN ({allowed}))')
    for table, column in NULLABLE.items():
        c.execute(f'ALTER TABLE {table} ALTER COLUMN {column} DROP NOT NULL')
    ddl = (ROOT / 'migrations/004_manual_prices.sql').read_text(encoding='utf-8')
    c.connection.execute(ddl.replace('id INTEGER PRIMARY KEY,', 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,'))
    c.execute(VIEW)
    c.execute('INSERT INTO schema_migrations(version) VALUES(4)')


def rebuild_sqlite(c, table, column, nullable, categories=False):
    """SQLite's documented create/copy/drop/rename sequence, with FKs off outside BEGIN."""
    definition = c.execute('SELECT sql FROM sqlite_master WHERE type=\'table\' AND name=?', (table,)).fetchone()[0]
    extras = [r[0] for r in c.execute('SELECT sql FROM sqlite_master WHERE tbl_name=? AND type IN (\'index\',\'trigger\') AND sql IS NOT NULL', (table,))]
    modified = definition
    if column:
        modified = re.sub(r'\b' + column + r'\s+INTEGER(?:\s+NOT\s+NULL)?', column + ' INTEGER' + ('' if nullable else ' NOT NULL'), modified, count=1, flags=re.I)
    if categories:
        allowed = CATEGORIES[table] + (",'procedure'" if nullable else '')
        modified = re.sub(r'CHECK\s*\(\s*category\s+IN\s*\([^)]*\)\s*\)', f'CHECK(category IN ({allowed}))', modified, flags=re.I)
    modified = re.sub(r'^(CREATE TABLE\s+(?:IF NOT EXISTS\s+)?)"?' + table + r'"?', r'\1c3_new_' + table, modified, count=1, flags=re.I)
    c.execute(modified)
    columns = ','.join('"' + r[1] + '"' for r in c.execute('PRAGMA table_info(' + table + ')'))
    c.execute(f'INSERT INTO c3_new_{table}({columns}) SELECT {columns} FROM {table}')
    c.execute('DROP TABLE ' + table)
    c.execute(f'ALTER TABLE c3_new_{table} RENAME TO {table}')
    for sql in extras:
        c.execute(sql)


def migrate_sqlite_manual_prices(path, *, down=False):
    c = sqlite3.connect(path, timeout=10)
    try:
        c.execute('PRAGMA foreign_keys=OFF')
        c.execute('BEGIN IMMEDIATE')
        applied = bool(c.execute('SELECT 1 FROM schema_migrations WHERE version=4').fetchone())
        if applied == (not down):
            c.rollback()
            return
        if down:
            down_guard(c)
        c.execute('DROP VIEW effective_charges')
        for table, column in NULLABLE.items():
            rebuild_sqlite(c, table, column, not down)
        rebuild_sqlite(c, 'service_categories', None, not down, categories=True)
        if down:
            c.execute(OLD_VIEW)
            c.execute('DROP TABLE manual_price_requests')
            c.execute('DROP TABLE manual_charge_prices')
            c.execute('ALTER TABLE service_catalog DROP COLUMN price_at_collection')
            c.execute('ALTER TABLE payments DROP COLUMN kind')
            c.execute('DROP INDEX IF EXISTS idx_charges_visit')
            c.execute('DELETE FROM schema_migrations WHERE version=4')
        else:
            c.execute('ALTER TABLE service_catalog ADD COLUMN price_at_collection INTEGER NOT NULL DEFAULT 0 CHECK(price_at_collection IN (0,1))')
            c.execute('ALTER TABLE payments ADD COLUMN ' + PAYMENT_KIND)
            c.execute("UPDATE payments SET kind='advance' WHERE is_advance=1")
            for sql in (ROOT / 'migrations/004_manual_prices.sql').read_text(encoding='utf-8').split(';'):
                if sql.strip():
                    c.execute(sql)
            c.execute(VIEW)
            c.execute('INSERT INTO schema_migrations(version) VALUES(4)')
        if c.execute('PRAGMA foreign_key_check').fetchone():
            raise ValueError('Kiểm tra khóa ngoại không đạt; đã hủy toàn bộ migration')
        c.commit()
    except Exception:
        c.rollback()
        raise
    finally:
        c.execute('PRAGMA foreign_keys=ON')
        c.close()
