"""Migration 020 records legacy completed visits and adds financial settlement history."""
from pathlib import Path


def migrate_settlements(c, postgres=False):
    if c.execute('SELECT 1 FROM schema_migrations WHERE version=20').fetchone():
        return
    ddl = (Path(__file__).resolve().parents[1] / 'migrations/020_visit_settlements.sql').read_text(encoding='utf-8')
    predecessor = ('FOREIGN KEY (visit_id, previous_settlement_id) '
                   'REFERENCES visit_settlement_reopens(visit_id, settlement_id)')
    if postgres:
        ddl = ddl.replace('INTEGER PRIMARY KEY AUTOINCREMENT', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    else:
        ddl = ddl.replace('UNIQUE (visit_id, id),', 'UNIQUE (visit_id, id),\n    ' + predecessor + ',')
    for statement in ddl.split(';'):
        if statement.strip():
            c.execute(statement)

    if postgres:
        c.execute('ALTER TABLE visit_settlements ADD ' + predecessor)
        c.connection.execute("""CREATE FUNCTION visit_settlement_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
            BEGIN RAISE EXCEPTION 'Không thể sửa hoặc xóa lịch sử kết thúc lượt'; END $$;""")
    for table in ('visit_settlements', 'visit_settlement_reopens'):
        if postgres:
            c.execute(f'''CREATE TRIGGER {table}_immutable BEFORE UPDATE OR DELETE ON {table}
                FOR EACH ROW EXECUTE FUNCTION visit_settlement_immutable()''')
            c.execute(f'''CREATE TRIGGER {table}_no_truncate BEFORE TRUNCATE ON {table}
                FOR EACH STATEMENT EXECUTE FUNCTION visit_settlement_immutable()''')
        else:
            for action in ('UPDATE', 'DELETE'):
                c.execute(f'''CREATE TRIGGER {table}_no_{action.lower()} BEFORE {action} ON {table}
                    BEGIN SELECT RAISE(ABORT,'Không thể sửa hoặc xóa lịch sử kết thúc lượt'); END''')
            # SQLite REPLACE can skip DELETE triggers on connections without recursive_triggers.
            if table == 'visit_settlements':
                conflict = '''id=NEW.id OR previous_settlement_id=NEW.previous_settlement_id
                    OR (visit_id=NEW.visit_id AND previous_settlement_id IS NULL AND NEW.previous_settlement_id IS NULL)'''
            else:
                conflict = 'settlement_id=NEW.settlement_id'
            c.execute(f'''CREATE TRIGGER {table}_no_replace BEFORE INSERT ON {table}
                WHEN EXISTS (SELECT 1 FROM {table} WHERE {conflict})
                BEGIN SELECT RAISE(ABORT,'Không thể thay thế lịch sử kết thúc lượt'); END''')
    # Chỉ lệnh INSERT trong migration được ghi danh sách tại thời điểm nâng cấp.
    if postgres:
        c.execute('''CREATE TRIGGER legacy_completed_visits_read_only
            BEFORE INSERT OR UPDATE OR DELETE OR TRUNCATE ON legacy_completed_visits
            FOR EACH STATEMENT EXECUTE FUNCTION visit_settlement_immutable()''')
    else:
        for action in ('INSERT', 'UPDATE', 'DELETE'):
            c.execute(f'''CREATE TRIGGER legacy_completed_visits_no_{action.lower()}
                BEFORE {action} ON legacy_completed_visits
                BEGIN SELECT RAISE(ABORT,'Không thể ghi danh sách lượt cũ'); END''')
    c.execute('INSERT INTO schema_migrations(version) VALUES(20)')
