import json
from datetime import datetime,timezone
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
ADDITIONS={
 'payments':[('is_advance','INTEGER NOT NULL DEFAULT 0 CHECK(is_advance IN (0,1))')],
 'service_catalog':[('code','TEXT'),('active','INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1))')],
 'medicines':[('code','TEXT'),('active','INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1))')],
 'orders':[('proposed_price','INTEGER NOT NULL DEFAULT 0'),('service_id','INTEGER REFERENCES service_catalog(id)')],
 'prescription_items':[('unit_name',"TEXT NOT NULL DEFAULT ''"),('unit_factor','INTEGER NOT NULL DEFAULT 1'),('unit_quantity','INTEGER NOT NULL DEFAULT 0')],
 'visit_nurses':[('active','INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1))')],
 'visit_addenda':[('base_version','INTEGER NOT NULL DEFAULT 0')],
}


def migrate_v050(c,postgres=False):
    if not postgres:c.execute('CREATE TABLE IF NOT EXISTS schema_migrations(version INTEGER PRIMARY KEY,applied_at TEXT)')
    if c.execute('SELECT 1 FROM schema_migrations WHERE version=3').fetchone():return
    for table,columns in ADDITIONS.items():
        if postgres:
            existing={r[0] for r in c.execute('SELECT column_name FROM information_schema.columns WHERE table_schema=\'public\' AND table_name=?',(table,))}
        else:existing={r[1] for r in c.execute('PRAGMA table_info('+table+')')}
        for name,definition in columns:
            if name not in existing:c.execute(f'ALTER TABLE {table} ADD COLUMN {name} {definition}')
    ddl=(ROOT/'migrations/003_v050.sql').read_text()
    if postgres:
        ddl=ddl.replace('id INTEGER PRIMARY KEY,','id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,')
        c.connection.execute(ddl)
    else:
        # executescript commits implicitly; execute each simple DDL statement to
        # keep schema and data backfills in the caller's transaction.
        for statement in ddl.split(';'):
            if statement.strip():c.execute(statement)
    for table,prefix in [('service_catalog','DV'),('medicines','TH')]:
        c.execute(f"UPDATE {table} SET code=? || CAST(id AS TEXT) WHERE code IS NULL",(prefix,))
        c.execute(f'CREATE UNIQUE INDEX idx_v050_{table}_code ON {table}(code)')
    c.execute("UPDATE orders SET service_id=(SELECT r.service_id FROM order_requests r WHERE r.order_id=orders.id) WHERE service_id IS NULL")
    c.execute("UPDATE orders SET proposed_price=COALESCE((SELECT ch.amount FROM charges ch JOIN charge_sources s ON s.charge_id=ch.id WHERE s.source_type='order' AND s.source_id=orders.id),0)")
    c.execute("INSERT INTO order_authorizations(order_id,service_id,unit_price,authorized_by,authorized_at) SELECT o.id,o.service_id,o.proposed_price,o.requested_by,o.created_at FROM orders o WHERE EXISTS(SELECT 1 FROM charge_sources s WHERE s.source_type='order' AND s.source_id=o.id)")
    c.execute('UPDATE prescription_items SET unit_quantity=quantity,unit_name=(SELECT m.base_unit FROM medicines m WHERE m.id=prescription_items.medicine_id)')
    now=datetime.now(timezone.utc).isoformat()
    last=0
    while True:
        rows=c.execute('SELECT * FROM visits WHERE id>? ORDER BY id LIMIT 200',(last,)).fetchall()
        if not rows:break
        for v in rows:
            data=dict(v)
            c.execute('INSERT INTO clinical_revisions(visit_id,version,snapshot,actor_id,reason,kind,created_at) VALUES(?,?,?,?,?,?,?)',(v['id'],v['version'],json.dumps(data,ensure_ascii=False),v['doctor_id'],'Giữ nguyên dữ liệu trước nâng cấp','migration',now))
            last=v['id']
    c.execute('INSERT INTO schema_migrations(version) VALUES(3)')
    if postgres:
        c.execute('ALTER TABLE charge_credits ADD CONSTRAINT v050_credit_return_fk FOREIGN KEY(source_id) REFERENCES medication_return_items(id)')
        c.connection.execute("""CREATE OR REPLACE FUNCTION minhduc_lock_clinical() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN IF OLD.status IN ('completed','cancelled') AND
        ((NEW.chief_complaint,NEW.history,NEW.vitals,NEW.diagnosis,NEW.treatment,NEW.follow_up) IS DISTINCT FROM
        (OLD.chief_complaint,OLD.history,OLD.vitals,OLD.diagnosis,OLD.treatment,OLD.follow_up) OR NEW.status IS DISTINCT FROM OLD.status)
        THEN RAISE EXCEPTION 'Closed clinical record is immutable' USING ERRCODE='23514'; END IF; RETURN NEW; END $$;
        CREATE TRIGGER v050_lock_clinical BEFORE UPDATE ON visits FOR EACH ROW EXECUTE FUNCTION minhduc_lock_clinical();""")
