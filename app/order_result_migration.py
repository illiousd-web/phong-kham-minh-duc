"""S1b version 14: preserve legacy text and its approval without touching orders."""
import json


def migrate_result_versions(c,postgres=False):
    if c.execute('SELECT 1 FROM schema_migrations WHERE version=14').fetchone():return
    identity='BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' if postgres else 'INTEGER PRIMARY KEY AUTOINCREMENT'
    c.execute(f'''CREATE TABLE order_result_versions(id {identity},order_id INTEGER NOT NULL REFERENCES orders(id),
      version INTEGER NOT NULL,result_text TEXT NOT NULL,created_by INTEGER REFERENCES users(id),created_at TEXT NOT NULL,
      approved_by INTEGER REFERENCES users(id),approved_at TEXT,snapshot TEXT,UNIQUE(order_id,version))''')
    for order in c.execute("SELECT * FROM orders WHERE result_text<>''").fetchall():
        approved=order['status']=='approved' or bool(order['approved_at'])
        value={'order_id':order['id'],'version':1,'result_text':order['result_text'],
               'created_by':order['result_by'],'created_at':order['created_at'],'approved_by':order['approved_by'],'approved_at':order['approved_at']}
        c.execute('INSERT INTO order_result_versions(order_id,version,result_text,created_by,created_at,approved_by,approved_at,snapshot) VALUES(?,?,?,?,?,?,?,?)',
                  (order['id'],1,order['result_text'],order['result_by'],order['created_at'],order['approved_by'],order['approved_at'],json.dumps(value,ensure_ascii=False) if approved else None))
    if postgres:
        c.connection.execute('''CREATE FUNCTION s1_text_result_guard() RETURNS trigger LANGUAGE plpgsql SET search_path=pg_catalog,public,pg_temp AS $$
          BEGIN
            IF TG_OP='DELETE' OR OLD.snapshot IS NOT NULL THEN RAISE EXCEPTION 'Phiên bản kết quả bất biến' USING ERRCODE='23514'; END IF;
            IF NEW.snapshot IS NULL OR NEW.approved_by IS NULL OR NEW.approved_at IS NULL OR
               (to_jsonb(NEW)-ARRAY['snapshot','approved_by','approved_at']) IS DISTINCT FROM
               (to_jsonb(OLD)-ARRAY['snapshot','approved_by','approved_at']) THEN
              RAISE EXCEPTION 'Chỉ được duyệt snapshot, không sửa nội dung phiên bản' USING ERRCODE='23514';
            END IF;
            RETURN NEW;
          END $$;
          CREATE TRIGGER s1_text_result_immutable BEFORE UPDATE OR DELETE ON order_result_versions FOR EACH ROW EXECUTE FUNCTION s1_text_result_guard();
          REVOKE ALL ON FUNCTION s1_text_result_guard() FROM PUBLIC;''')
    c.execute('INSERT INTO schema_migrations(version) VALUES(14)')
