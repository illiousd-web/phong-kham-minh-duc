"""S2d v19: imaging templates and report revisions on existing orders."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _review_guards(c, postgres):
    # This PR's unreleased v19 can already exist in a review/test database.
    if postgres:
        has_editor = c.execute("SELECT 1 FROM information_schema.columns WHERE table_schema=current_schema() AND table_name='imaging_reports' AND column_name='updated_by'").fetchone()
    else:
        has_editor = any(row[1]=='updated_by' for row in c.execute('PRAGMA table_info(imaging_reports)'))
    if not has_editor:
        c.execute('ALTER TABLE imaging_reports ADD COLUMN updated_by INTEGER REFERENCES users(id)')
        # Signed snapshots stay immutable; only old drafts need an initial editor.
        c.execute('UPDATE imaging_reports SET updated_by=created_by WHERE snapshot IS NULL')
    if not postgres:
        c.execute("CREATE TRIGGER IF NOT EXISTS s2d_image_no_replace BEFORE INSERT ON imaging_images WHEN EXISTS(SELECT 1 FROM imaging_images WHERE id=NEW.id) BEGIN SELECT RAISE(ABORT,'Không thay thế ảnh'); END")


def migrate_s2d(c, postgres=False):
    if c.execute('SELECT 1 FROM schema_migrations WHERE version=19').fetchone():
        _review_guards(c, postgres)
        return
    identity = 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' if postgres else 'INTEGER PRIMARY KEY AUTOINCREMENT'
    c.execute('''CREATE TABLE imaging_templates(code TEXT PRIMARY KEY, category TEXT NOT NULL,
        name TEXT NOT NULL, content TEXT NOT NULL, active INTEGER NOT NULL DEFAULT 1 CHECK(active IN (0,1)))''')
    for i, item in enumerate(json.loads((ROOT/'data/danh_muc_goc/mau_ket_qua_28.json').read_text(encoding='utf-8')), 1):
        c.execute('INSERT INTO imaging_templates(code,category,name,content) VALUES(?,?,?,?)',
                  (f'S2D-{i:03}', 'xray' if item['xq'] else 'ultrasound', item['n'], json.dumps(item, ensure_ascii=False)))
    c.execute(f'''CREATE TABLE imaging_reports(id {identity}, order_id INTEGER NOT NULL REFERENCES orders(id),
        template_code TEXT NOT NULL REFERENCES imaging_templates(code), descriptions TEXT NOT NULL,
        request TEXT NOT NULL, conclusion TEXT NOT NULL DEFAULT '', advice TEXT NOT NULL DEFAULT '', version INTEGER NOT NULL DEFAULT 0,
        created_by INTEGER NOT NULL REFERENCES users(id), created_at TEXT NOT NULL, updated_at TEXT NOT NULL,
        updated_by INTEGER REFERENCES users(id),
        replaces_id INTEGER UNIQUE REFERENCES imaging_reports(id), reason TEXT NOT NULL DEFAULT '', snapshot TEXT)''')
    c.execute('CREATE INDEX idx_imaging_order ON imaging_reports(order_id,id)')
    c.execute(f'''CREATE TABLE imaging_images(id {identity}, report_id INTEGER NOT NULL REFERENCES imaging_reports(id),
        file_key TEXT NOT NULL, sha256 TEXT NOT NULL, media_type TEXT NOT NULL,
        created_by INTEGER NOT NULL REFERENCES users(id), created_at TEXT NOT NULL)''')
    # Expand the existing signing store, retaining its evidence and immutable guards.
    if postgres:
        c.execute('ALTER TABLE document_signatures DROP CONSTRAINT document_signatures_document_kind_check')
        c.execute("ALTER TABLE document_signatures ADD CHECK(document_kind IN ('rx','order','lab','clinical_rx','lab_report','ultrasound','xray'))")
        c.connection.execute('''CREATE FUNCTION s2d_report_guard() RETURNS trigger LANGUAGE plpgsql AS $$
            BEGIN IF TG_OP='DELETE' OR OLD.snapshot IS NOT NULL THEN
                RAISE EXCEPTION 'Phiếu đã ký bất biến' USING ERRCODE='23514'; END IF; RETURN NEW; END $$;
            CREATE TRIGGER s2d_report_guard BEFORE UPDATE OR DELETE ON imaging_reports FOR EACH ROW EXECUTE FUNCTION s2d_report_guard();
            CREATE FUNCTION s2d_image_guard() RETURNS trigger LANGUAGE plpgsql AS $$
            BEGIN IF TG_OP<>'DELETE' AND EXISTS(SELECT 1 FROM imaging_reports WHERE id=NEW.report_id AND snapshot IS NOT NULL) THEN
                RAISE EXCEPTION 'Ảnh phiếu đã ký bất biến' USING ERRCODE='23514'; END IF;
                IF TG_OP<>'INSERT' AND EXISTS(SELECT 1 FROM imaging_reports WHERE id=OLD.report_id AND snapshot IS NOT NULL) THEN
                RAISE EXCEPTION 'Ảnh phiếu đã ký bất biến' USING ERRCODE='23514'; END IF;
                IF TG_OP='DELETE' THEN RETURN OLD; END IF; RETURN NEW; END $$;
            CREATE TRIGGER s2d_image_guard BEFORE INSERT OR UPDATE OR DELETE ON imaging_images FOR EACH ROW EXECUTE FUNCTION s2d_image_guard();
            REVOKE ALL ON FUNCTION s2d_report_guard(), s2d_image_guard() FROM PUBLIC;''')
    else:
        ddl = (ROOT/'migrations/017_s2c_signatures.sql').read_text(encoding='utf-8')
        table = ddl[:ddl.index(';')].replace('CREATE TABLE document_signatures', 'CREATE TABLE s2d_signatures')
        table = table.replace("'lab_report'", "'lab_report','ultrasound','xray'")
        c.execute(table)
        c.execute('INSERT INTO s2d_signatures SELECT * FROM document_signatures')
        c.execute('DROP TABLE document_signatures')
        c.execute('ALTER TABLE s2d_signatures RENAME TO document_signatures')
        for statement in ddl[ddl.index(';')+1:].split(';'):
            if statement.strip():
                c.execute(statement)
        for event in ('UPDATE', 'DELETE'):
            c.execute(f"CREATE TRIGGER s2c_signature_guard_{event.lower()} BEFORE {event} ON document_signatures BEGIN SELECT RAISE(ABORT,'Không thể sửa hoặc xóa bản ký'); END")
        from .s2c_migration import _sqlite_insert_guard
        _sqlite_insert_guard(c)
        c.execute("CREATE TRIGGER s2d_report_update BEFORE UPDATE ON imaging_reports WHEN OLD.snapshot IS NOT NULL BEGIN SELECT RAISE(ABORT,'Phiếu đã ký bất biến'); END")
        c.execute("CREATE TRIGGER s2d_report_delete BEFORE DELETE ON imaging_reports BEGIN SELECT RAISE(ABORT,'Không xóa lịch sử phiếu'); END")
        for event in ('UPDATE', 'DELETE'):
            c.execute(f"CREATE TRIGGER s2d_image_{event.lower()} BEFORE {event} ON imaging_images WHEN EXISTS(SELECT 1 FROM imaging_reports WHERE id=OLD.report_id AND snapshot IS NOT NULL) BEGIN SELECT RAISE(ABORT,'Ảnh phiếu đã ký bất biến'); END")
        c.execute("CREATE TRIGGER s2d_report_no_replace BEFORE INSERT ON imaging_reports WHEN EXISTS(SELECT 1 FROM imaging_reports WHERE id=NEW.id) BEGIN SELECT RAISE(ABORT,'Không thay thế phiếu'); END")
        for event in ('INSERT','UPDATE'):
            c.execute(f"CREATE TRIGGER s2d_image_new_{event.lower()} BEFORE {event} ON imaging_images WHEN EXISTS(SELECT 1 FROM imaging_reports WHERE id=NEW.report_id AND snapshot IS NOT NULL) BEGIN SELECT RAISE(ABORT,'Ảnh phiếu đã ký bất biến'); END")
    _review_guards(c, postgres)
    c.execute('INSERT INTO schema_migrations(version) VALUES(19)')
