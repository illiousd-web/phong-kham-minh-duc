"""Atomic S2b v16 upgrade; unknown legacy costs stay NULL, never zero."""
from pathlib import Path

ADDED = {
    'medicines': ('min_stock',),
    'stock_lots': ('unit_cost', 'vat_rate', 'receipt_id'),
    'stock_movements': ('unit_cost', 'vat_rate', 'revenue_amount', 'receipt_id', 'issue_id'),
}
IMMUTABLE = ('stock_receipts', 'stock_issues', 'stock_movements')


def restore_s2b_function_acl(c):
    """Owner-only: pg_restore --no-acl omits this private trigger-function ACL.

    Backups before 016 have no such function; never migrate a restored old schema.
    """
    if c.execute("SELECT to_regprocedure('public.s2b_stock_immutable()') IS NOT NULL").fetchone()[0]:
        c.execute('REVOKE ALL ON FUNCTION public.s2b_stock_immutable() FROM PUBLIC')


def migrate_s2b(c, postgres=False, *, down=False):
    applied = bool(c.execute('SELECT 1 FROM schema_migrations WHERE version=16').fetchone())
    if applied == (not down):
        return
    if down:
        # Do not silently discard financial evidence or new configuration.
        checks = [f'SELECT 1 FROM {table} WHERE ' + ' OR '.join(f'{col} IS NOT NULL' for col in cols) + ' LIMIT 1'
                  for table, cols in ADDED.items()]
        checks += ['SELECT 1 FROM stock_receipts LIMIT 1', 'SELECT 1 FROM stock_issues LIMIT 1',
                   "SELECT 1 FROM user_roles WHERE role='stock_owner' LIMIT 1"]
        if any(c.execute(query).fetchone() for query in checks):
            raise ValueError('Chưa quay lui S2b: đã có dữ liệu kho mới. Khôi phục bản sao lưu trước nâng cấp để giữ dữ liệu.')
        for table in IMMUTABLE:
            c.execute(f'DROP TRIGGER s2b_{table}_update' + (f' ON {table}' if postgres else ''))
            c.execute(f'DROP TRIGGER s2b_{table}_delete' + (f' ON {table}' if postgres else ''))
            if postgres:
                c.execute(f'DROP TRIGGER s2b_{table}_truncate ON {table}')
        if postgres:
            c.execute('DROP FUNCTION s2b_stock_immutable()')
        for index in ('time', 'receipt', 'issue'):
            c.execute(f'DROP INDEX idx_s2b_movement_{index}')
        for table, columns in ADDED.items():
            for column in reversed(columns):
                c.execute(f'ALTER TABLE {table} DROP COLUMN {column}')
        for table in ('stock_document_sequences', 'stock_issues', 'stock_receipts'):
            c.execute(f'DROP TABLE {table}')
        c.execute('DELETE FROM schema_migrations WHERE version=16')
        return
    ddl = (Path(__file__).resolve().parents[1] / 'migrations/016_s2b_stock.sql').read_text(encoding='utf-8')
    if postgres:
        ddl = ddl.replace('id INTEGER PRIMARY KEY,', 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,')
    for statement in ddl.split(';'):
        if statement.strip():
            c.execute(statement)
    if postgres:
        c.connection.execute("""CREATE FUNCTION s2b_stock_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
        BEGIN RAISE EXCEPTION 'Phiếu kho và biến động đã lưu không được sửa/xóa' USING ERRCODE='23514'; END $$;""")
        restore_s2b_function_acl(c)
    for table in IMMUTABLE:
        for event in ('UPDATE', 'DELETE'):
            trigger = f's2b_{table}_{event.lower()}'
            if postgres:
                c.execute(f'CREATE TRIGGER {trigger} BEFORE {event} ON {table} FOR EACH ROW EXECUTE FUNCTION s2b_stock_immutable()')
            else:
                c.execute(f"CREATE TRIGGER {trigger} BEFORE {event} ON {table} BEGIN SELECT RAISE(ABORT,'Phiếu kho và biến động đã lưu không được sửa/xóa'); END")
        if postgres:
            c.execute(f'CREATE TRIGGER s2b_{table}_truncate BEFORE TRUNCATE ON {table} FOR EACH STATEMENT EXECUTE FUNCTION s2b_stock_immutable()')
    c.execute('INSERT INTO schema_migrations(version) VALUES(16)')


if __name__ == '__main__':
    import argparse
    import sqlite3
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--sqlite', required=True, type=Path)
    parser.add_argument('--down', action='store_true')
    args = parser.parse_args()
    if not args.sqlite.is_file():
        parser.error('Không có CSDL SQLite để nâng cấp / quay lui')
    with sqlite3.connect(args.sqlite) as connection:
        connection.execute('PRAGMA foreign_keys=ON')
        connection.execute('BEGIN IMMEDIATE')
        migrate_s2b(connection, down=args.down)
