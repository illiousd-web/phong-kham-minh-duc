"""M6/L3, additive migration 8: clinical prescriptions, never money or stock."""
TABLES = ('drugs', 'clinical_prescriptions', 'clinical_prescription_items', 'prescription_outbox', 'prescription_settings')


def migrate_m6(c, postgres=False):
    if c.execute('SELECT 1 FROM schema_migrations WHERE version=8').fetchone():
        return
    identity = 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' if postgres else 'INTEGER PRIMARY KEY AUTOINCREMENT'
    statements = [
        f'''CREATE TABLE drugs(id {identity}, name TEXT NOT NULL, name_key TEXT NOT NULL,
            ingredient TEXT NOT NULL DEFAULT '', ingredient_key TEXT NOT NULL DEFAULT '', brand_name TEXT NOT NULL DEFAULT '', strength TEXT NOT NULL DEFAULT '',
            strength_key TEXT NOT NULL, dosage_form TEXT NOT NULL DEFAULT '', route TEXT NOT NULL DEFAULT '',
            unit TEXT NOT NULL DEFAULT '', registration_number TEXT NOT NULL DEFAULT '', national_code TEXT,
            manufacturer TEXT NOT NULL DEFAULT '', notes TEXT NOT NULL DEFAULT '', toxic INTEGER NOT NULL DEFAULT 0,
            controlled_type TEXT NOT NULL DEFAULT '' CHECK(controlled_type IN ('','N','H','precursor')),
            review_status TEXT NOT NULL DEFAULT 'unreviewed' CHECK(review_status IN ('unreviewed','reviewed','inactive')),
            merged_into INTEGER REFERENCES drugs(id), UNIQUE(name_key,strength_key))''',
        f'''CREATE TABLE clinical_prescriptions(id {identity}, visit_id INTEGER NOT NULL REFERENCES visits(id),
            doctor_id INTEGER NOT NULL REFERENCES users(id), status TEXT NOT NULL DEFAULT 'draft'
            CHECK(status IN ('draft','locked','cancelled')), version INTEGER NOT NULL DEFAULT 0,
            lifestyle_advice TEXT NOT NULL DEFAULT '', follow_up_advice TEXT NOT NULL DEFAULT '',
            purchase_advice TEXT NOT NULL DEFAULT '', replaces_id INTEGER REFERENCES clinical_prescriptions(id),
            local_code TEXT UNIQUE, national_code TEXT, snapshot TEXT, created_at TEXT NOT NULL,
            locked_at TEXT, cancelled_at TEXT, cancellation_reason TEXT)''',
        f'''CREATE TABLE clinical_prescription_items(id {identity}, prescription_id INTEGER NOT NULL REFERENCES clinical_prescriptions(id),
            drug_id INTEGER NOT NULL REFERENCES drugs(id), position INTEGER NOT NULL, content TEXT NOT NULL,
            UNIQUE(prescription_id,position))''',
        f'''CREATE TABLE prescription_outbox(id {identity}, prescription_id INTEGER NOT NULL UNIQUE REFERENCES clinical_prescriptions(id),
            schema_version TEXT NOT NULL, payload TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'pending',
            national_code TEXT, created_at TEXT NOT NULL)''',
        '''CREATE TABLE prescription_settings(key TEXT PRIMARY KEY, value TEXT NOT NULL)''',
        'CREATE INDEX idx_m6_queue ON clinical_prescriptions(status,doctor_id,id)',
        'CREATE INDEX idx_m6_visit ON clinical_prescriptions(visit_id,id)',
        'CREATE INDEX idx_m6_drug_items ON clinical_prescription_items(drug_id)',
        'CREATE INDEX idx_m6_review ON drugs(review_status,id)',
    ]
    for statement in statements:
        c.execute(statement)
    c.execute('INSERT INTO schema_migrations(version) VALUES(8)')
